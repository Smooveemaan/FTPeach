// Removes build caches and generated output; the next build recreates them.
//   npm run clean [-- --dry-run] [-- --artifacts-only]
// --artifacts-only keeps the native compilation caches. Deliberately kept
// always: .local and node_modules.
import { lstatSync, rmSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';

interface Target {
  label: string;
  path: string;
  /** A Cargo target directory, kept by --artifacts-only. */
  native?: boolean;
}

export function cleanTargets(root: string, localAppData = process.env.LOCALAPPDATA): Target[] {
  const at = (label: string, native = false): Target => ({
    label,
    path: path.join(root, ...label.split('/')),
    native,
  });
  const targets = [
    // Default Cargo target directory (dev, check, test, clippy).
    at('src-tauri/target', true),
    at('src-tauri/fuzz/target', true),
    // Cargo target directories of `smoke-build` and `test-installers` (scripts/cargo.ts).
    at('.tools/smoke-target', true),
    at('.tools/installer-target', true),
    // Signed test installers of scripts/release/test-installers.ts.
    at('.tools/installer-test'),
    // Vite output checked by scripts/checks/check-bundle-budget.ts.
    at('dist'),
    // The website of scripts/site/build.ts.
    at('dist-site'),
    // SBOM output of scripts/release/generate-sbom.ts.
    at('release'),
    // Playwright output (playwright.config.ts).
    at('test-results'),
    at('playwright-report'),
    at('coverage'),
    at('duplication-report'),
    at('src-tauri/fuzz/coverage'),
    // Tauri-generated schemas.
    at('src-tauri/gen'),
    at('src-tauri/permissions/autogenerated'),
  ];
  // Cargo target directory of `build` on Windows (scripts/cargo.ts), outside the repository.
  if (process.platform === 'win32' && localAppData) {
    targets.push({
      label: '%LOCALAPPDATA%\\FTPeachBuild',
      path: path.join(localAppData, 'FTPeachBuild'),
      native: true,
    });
  }
  return targets;
}

export function clean(targets: Target[], options: { artifactsOnly: boolean; dryRun: boolean }) {
  for (const target of targets) {
    if (options.artifactsOnly && target.native) continue;
    let isLink: boolean;
    try {
      isLink = lstatSync(target.path).isSymbolicLink();
    } catch {
      console.log(`skip    ${target.label} (not present)`);
      continue;
    }
    // Node reports Windows junctions as symbolic links too.
    if (isLink)
      throw new Error(`Cleanup target must not be a symbolic link or junction: ${target.path}`);
    if (options.dryRun) {
      console.log(`would remove ${target.label}`);
      continue;
    }
    try {
      rmSync(target.path, { recursive: true, force: true, maxRetries: 2 });
      console.log(`removed ${target.label}`);
    } catch (error) {
      // Individual files can be locked (rust-analyzer, a running dev build,
      // antivirus): report and go on with the rest.
      console.warn(
        `${target.label}: left behind by locked files (${(error as Error).message}) - close the app, dev server, or rust-analyzer and re-run.`,
      );
    }
  }
}

if (import.meta.filename === process.argv[1]) {
  const args = process.argv.slice(2);
  const unknown = args.filter((arg) => arg !== '--dry-run' && arg !== '--artifacts-only');
  if (unknown.length > 0) {
    console.error(
      `Unknown argument ${unknown[0]}; the options are at the top of scripts/clean.ts.`,
    );
    process.exit(2);
  }
  clean(cleanTargets(path.resolve(import.meta.dirname, '..')), {
    artifactsOnly: args.includes('--artifacts-only'),
    dryRun: args.includes('--dry-run'),
  });
}
